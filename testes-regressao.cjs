'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const cadastro = fs.readFileSync('cadastro.js', 'utf8');
const servicos = fs.readFileSync('servicos.js', 'utf8');
const conversa = fs.readFileSync('conversa.js', 'utf8');
const ambiente = fs.readFileSync('ambiente.js', 'utf8');
assert.match(html, /<script src="transicoes-contratacao\.js" defer><\/script>/);
assert.ok(html.indexOf('transicoes-contratacao.js') < html.indexOf('servicos.js'));
assert.match(cadastro, /confirmacao\.elements\.token\.disabled = false/);
assert.match(servicos, /sessaoServicos !== sessaoDaBusca/);
assert.match(servicos, /sessaoServicos !== sessaoOriginal \|\| profissionalEscolhido !== profissionalOriginal/);
assert.match(servicos, /Array\.isArray\(registros\)/);
assert.match(servicos, /select: 'id,titulo,descricao'/);
assert.match(servicos, /registros\[0\]\.titulo === titulo && registros\[0\]\.descricao === descricao/);
assert.match(servicos, /let versaoBusca = 0/);
assert.match(servicos, /let versaoLogin = 0/);
assert.match(servicos, /const loginAtual = \+\+versaoLogin/);
assert.match(servicos, /if \(loginAtual !== versaoLogin\) return/);
assert.match(servicos, /if \(!filtrosBusca \|\| maisProfissionais\.hidden\) return/);
assert.match(servicos, /const filtrosAtuais = \{ \.\.\.filtros \}/);
assert.match(servicos, /if \(buscaAtual !== versaoBusca\) return/);
assert.match(servicos, /if \(sessaoServicos !== sessaoDaBusca\) return;/);
assert.match(servicos, /if \(sessaoServicos === sessaoOriginal\) await carregarPedidos\(aviso\)/);
assert.match(conversa, /sessaoServicos !== sessaoOriginal \|\| pedidoEmConversa !== pedidoOriginal/);
assert.match(ambiente, /config\.ambiente !== 'homologacao'/);
const config = fs.readFileSync('config.js', 'utf8');
assert.match(config, /autenticacaoPronta:\s*false/, 'Login não deve ser liberado sem validação do Supabase.');
assert.match(config, /ambiente:\s*'homologacao'/);
assert.match(html, /Pagamentos online ainda não estão disponíveis/);
assert.match(html, /Nenhuma cobrança está habilitada/);
assert.doesNotMatch(html, /<script[^>]+src="https?:\/\//i, 'Não carregar scripts externos sem revisão.');
assert.match(servicos, /Esta ação não realiza pagamento nem reserva dinheiro/);
assert.match(servicos, /nenhum pagamento foi processado/i);
console.log('Verificacoes de regressao da interface aprovadas.');
